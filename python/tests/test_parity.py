class TestSavingsParity:
    def test_savings_count_and_total(self, fixtures):
        savings = build_savings_opportunities()
        assert len(savings) == fixtures["savings"]["totalCount"]
        total = round(sum(s.monthlySavings for s in savings), 2)
        assert total == fixtures["savings"]["totalMonthlySavings"]

    def test_aws_savings(self, fixtures):
        aws = get_savings({"providers": ["AWS"]})
        assert len(aws) == fixtures["savings"]["awsCount"]
        total = round(sum(s.monthlySavings for s in aws), 2)
        assert total == fixtures["savings"]["awsTotalMonthlySavings"]

    def test_ml_savings(self, fixtures):
        ml = get_savings({"teams": ["ml"]})
        assert len(ml) == fixtures["savings"]["mlCount"]
        total = round(sum(s.monthlySavings for s in ml), 2)
        assert total == fixtures["savings"]["mlTotalMonthlySavings"]

    def test_resource_id_presence(self, fixtures):
        savings = build_savings_opportunities()
        by_id = {s.id: s for s in savings}
        for entry in fixtures["savings"]["resourceIdPresence"]:
            s = by_id[entry["id"]]
            has_id = s.resourceId is not None
            assert has_id == entry["hasResourceId"], (
                f"{entry['id']}: resourceId presence {has_id} != {entry['hasResourceId']}"
            )

    def test_savings_serialization_parity(self, fixtures):
        savings = build_savings_opportunities()
        for s in savings:
            if s.resourceId is None:
                # TS serializes undefined as missing key — Python should omit it
                data = {
                    "id": s.id,
                    "title": s.title,
                    "category": s.category,
                    "provider": s.provider,
                    "service": s.service,
                    "team": s.team,
                    "product": s.product,
                    "monthlySavings": round(s.monthlySavings, 2),
                    "currency": s.currency,
                    "recommendedAction": s.recommendedAction,
                    "effort": s.effort,
                    "details": s.details,
                }
                assert "resourceId" not in data


