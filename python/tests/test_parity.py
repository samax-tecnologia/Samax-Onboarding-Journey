class TestMulberry32Parity:
    def test_prng_determinism(self, fixtures):
        for seed, expected_outputs in zip(
            fixtures["prng"]["seeds"],
            fixtures["prng"]["outputs"],
        ):
            rand = mulberry32(seed)
            for expected in expected_outputs:
                actual = round(rand(), 4)
                assert actual == expected, (
                    f"mulberry32({seed}): expected {expected}, got {actual}"
                )


